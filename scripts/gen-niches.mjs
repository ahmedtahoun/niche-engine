// Writes apps/web/src/lib/niche-files.generated.ts: every niches/*.json as a static import.
// Cloudflare Workers have no file system at runtime, so the niche settings are bundled into the app.
// Runs before every build (apps/web "build" script); commit the result so dev and typecheck work too.
import { readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = readdirSync(path.join(root, 'niches')).filter((f) => f.endsWith('.json')).sort();
const id = (f) => 'n_' + f.replace(/\.json$/, '').replace(/[^a-zA-Z0-9]/g, '_');
const out = [
  '// Generated by scripts/gen-niches.mjs from niches/*.json. Do not edit by hand.',
  ...files.map((f) => `import ${id(f)} from '../../../../niches/${f}' with { type: 'json' };`),
  '',
  'export const nicheFiles: Record<string, unknown> = {',
  ...files.map((f) => `  '${f}': ${id(f)},`),
  '};',
  '',
].join('\n');
writeFileSync(path.join(root, 'apps/web/src/lib/niche-files.generated.ts'), out);
console.log(`niche-files.generated.ts: ${files.length} niches`);
