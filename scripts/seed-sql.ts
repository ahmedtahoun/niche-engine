// Writes supabase/seed/coffee-bonds.sql from apps/web/src/lib/seeds/bonds.ts.
//   node scripts/seed-sql.ts
// Run the SQL once in Supabase → SQL Editor. Running it again updates names, texts
// and prices but keeps stock, status, views and the seller's Telegram chat.
import { writeFileSync } from 'node:fs';
import { BONDS, BONDS_PRODUCTS } from '../apps/web/src/lib/seeds/bonds.ts';
import { productToRow, sellerToRow } from '../apps/web/src/lib/store/rows.ts';
import { readFileSync } from 'node:fs';

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'object') return `${q(JSON.stringify(v))}::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

const insert = (table: string, row: Record<string, unknown>, update: string[]) => {
  const cols = Object.keys(row);
  return `insert into ${table} (${cols.join(', ')})\nvalues (${cols.map((c) => q(row[c])).join(', ')})\non conflict (id) do update set ${update.map((c) => `${c} = excluded.${c}`).join(', ')};`;
};

const cfg = JSON.parse(readFileSync(new URL('../niches/coffee.json', import.meta.url), 'utf8'));
const seller = sellerToRow(BONDS) as unknown as Record<string, unknown>;
delete seller.telegram_chat_id; // set by linking the seller's Telegram (see the note at the end)
const products = BONDS_PRODUCTS.map((p) => { const r = productToRow(p) as unknown as Record<string, unknown>; delete r.price_confirmed_at; return r; });

const sql = `-- Cairo Roast: Bonds Coffee Roasters and its 5 coffees.
-- Generated by scripts/seed-sql.ts. Run once in Supabase → SQL Editor (safe to run again).
begin;

-- English texts (same as migration 0005, so this file works on its own).
alter table products add column if not exists en jsonb;
alter table sellers add column if not exists name_en text;

insert into niches (id, status, config) values ('coffee', ${q(cfg.status)}, ${q(cfg)})
on conflict (id) do nothing;

${insert('sellers', seller, ['store_name', 'name_en', 'instagram', 'area', 'governorate'])}

${products.map((r) => insert('products', r, ['name_ar', 'lead_ar', 'category', 'art', 'color', 'price', 'attributes', 'faq', 'en'])).join('\n\n')}

-- Prices per weight live inside "variants". On a re-run, refresh them without touching stock:
${BONDS_PRODUCTS.map((p) => `update products set variants = (select jsonb_agg(case ${p.variants.map((v) => `when e->>'label' = ${q(v.label)} then e || ${q({ price: v.price, opts: v.opts, ...(v.labelEn ? { labelEn: v.labelEn } : {}) })}`).join(' ')} else e end) from jsonb_array_elements(variants) e) where id = ${q(p.id)};`).join('\n')}

commit;

-- To receive Bonds' orders on Telegram: open the bot from the Telegram account that
-- handles Bonds orders, send /myid, then run (with that number):
--   update sellers set telegram_chat_id = 123456789 where id = 'bonds';
`;
writeFileSync(new URL('../supabase/seed/coffee-bonds.sql', import.meta.url), sql);
console.log('wrote supabase/seed/coffee-bonds.sql');
